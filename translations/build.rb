# frozen_string_literal: true

# Builds kitchen_cabinet_master/html/lang/<code>.js from translations/<code>.txt: one translation per line, in the order of keys.txt (the English words
# of the panel). A line left empty keeps the English. Run:  ruby translations/build.rb
require 'json'
require 'fileutils'

ROOT = File.expand_path('..', __dir__)
KEYS = File.read(File.join(__dir__, 'keys.txt'), encoding: 'UTF-8').lines.map(&:chomp).reject(&:empty?)
OUT = File.join(ROOT, 'kitchen_cabinet_master', 'html', 'lang')
FileUtils.mkdir_p(OUT)

problems = []
Dir[File.join(__dir__, '*.txt')].sort.each do |path|
  code = File.basename(path, '.txt')
  next if code == 'keys'

  lines = File.read(path, encoding: 'UTF-8').lines.map(&:chomp)
  lines.pop while lines.last == ''
  if lines.length != KEYS.length
    problems << "#{code}: #{lines.length} lines for #{KEYS.length} keys"
    next
  end
  table = KEYS.zip(lines).reject { |_, text| text.strip.empty? }.to_h
  File.write(File.join(OUT, "#{code}.js"), "// generated by translations/build.rb from translations/#{code}.txt\n(window.KCM_LANG = window.KCM_LANG || {}).#{code} = #{JSON.generate(table)};\n", encoding: 'UTF-8')
  puts "#{code}: #{table.length} words"
end
abort(problems.join("\n")) unless problems.empty?
